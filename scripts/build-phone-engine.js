#!/usr/bin/env node
// Build the phone app's engine module.
//
// The phone build (a Claude Design canvas) loads one flat ES module, so it
// cannot `import` the repo's `src/` directly. The version that shipped was a
// hand-reduced copy of `src/codex.js` alone: it named seven reading layers and
// computed four of them. Hand-copying is what let that drift open, so this
// script assembles the module instead — `src/` stays canonical, `src-phone/`
// holds only what is genuinely phone-only (renderers, Keplerian planets, the
// ephemeris client, the display overlay), and any divergence shows up here as a
// build failure rather than as prose in the interface.
//
//   node scripts/build-phone-engine.js [--check]
//
// --check verifies the committed output is current without rewriting it.

import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const output = join(root, 'dist-phone', 'codex-data.js')

// Dependency order. Concatenation is only safe because every file is an ES
// module with no side effects at import time except the display overlay, which
// is invoked explicitly in the footer below.
const SOURCES = [
  'src/astrology.js',
  'src/codex.js',
  'src/chart.js',
  'src/sky.js',
  'src/gates.js',
  'src/reading.js',
  'src/synthesis.js',
  'src/synthesis-packet.js',
  'src-phone/display.js',
  'src-phone/places.js',
  'src-phone/keplerian.js',
  'src-phone/lineages.js',
  'src-phone/render.js',
  'src-phone/ephemeris.js',
  'src-phone/sample.js',
  'src-phone/reading-pass.js',
]

// The exact surface the shipped phone build exposed. The interface calls 17 of
// these by name; the rest are kept because removing an export is a breaking
// change we should have to argue for, not one a refactor can make silently.
const REQUIRED_EXPORTS = [
  'GROUPS', 'CHORDS', 'parseCodex', 'seamCounterpart', 'parseLineages',
  'angularSeparation', 'conjunction', 'decagonalChord', 'computeSampleReading',
  'sigilDataUri', 'lineageSigilDataUri', 'wheelDataUri', 'wheelSeatPosition',
  'julianDate', 'planetLongitudes', 'fixtureLongitudes', 'uniqueBodies',
  'fetchGlyphLongitudes', 'computeReading', 'dodecaFaceDataUri', 'dodecaFaces',
  'chordSigilDataUri', 'latticeDataUri', 'moonLongitude', 'HORIZONS_ENDPOINT',
  'horizonsUrl', 'parseHorizonsPlacement', 'fetchGlyphLongitudesDirect',
  'chordDestinations',
]

const IMPORT_LINE = /^\s*import\s+[^'"]*from\s*['"][^'"]+['"]\s*;?\s*$/gm

function stripImports(source) {
  return source.replace(IMPORT_LINE, '')
}

// Top-level declarations only: a duplicate here is a real collision (two
// definitions of the same name in one module scope), which JS would reject at
// parse time with a message that points at the generated file rather than at
// the source that introduced it.
function topLevelNames(source) {
  const names = []
  const pattern = /^(?:export\s+)?(?:async\s+)?(function|const|let|class)\s+([A-Za-z_$][\w$]*)/gm
  let match
  while ((match = pattern.exec(source))) names.push(match[2])
  return names
}

function exportedNames(source) {
  const names = []
  const pattern = /^export\s+(?:async\s+)?(?:function|const|let|class)\s+([A-Za-z_$][\w$]*)/gm
  let match
  while ((match = pattern.exec(source))) names.push(match[1])
  return names
}

const seen = new Map()
const collisions = []
const chunks = []

for (const relative of SOURCES) {
  const path = join(root, relative)
  if (!existsSync(path)) {
    console.error(`missing source: ${relative}`)
    process.exit(1)
  }
  const body = stripImports(readFileSync(path, 'utf8')).trim()
  for (const name of topLevelNames(body)) {
    if (seen.has(name)) collisions.push({ name, first: seen.get(name), second: relative })
    else seen.set(name, relative)
  }
  chunks.push(`// ─────────────────────────────────────────────────────────────\n// ${relative}\n// ─────────────────────────────────────────────────────────────\n\n${body}\n`)
}

if (collisions.length) {
  console.error('duplicate top-level declarations — the canon and the phone source have drifted:')
  for (const c of collisions) console.error(`  ${c.name}: ${c.first} and ${c.second}`)
  process.exit(1)
}

const header = `// GENERATED by scripts/build-phone-engine.js — do not edit.
//
// Assembled from the canon in src/ plus the phone-only modules in src-phone/.
// Rebuild with:  node scripts/build-phone-engine.js
// Verify with:   node scripts/build-phone-engine.js --check
//
// Sources, in dependency order:
${SOURCES.map(source => `//   ${source}`).join('\n')}
`

const footer = `
// ─────────────────────────────────────────────────────────────
// phone display overlay (applied once, at module init)
// ─────────────────────────────────────────────────────────────

applyPhoneDisplay(GROUPS, CHORDS)
`

const generated = [header, ...chunks, footer].join('\n')

const produced = exportedNames(generated)
const missing = REQUIRED_EXPORTS.filter(name => !produced.includes(name))
if (missing.length) {
  console.error(`export surface regression — the phone interface imports these by name:\n  ${missing.join(', ')}`)
  process.exit(1)
}

if (process.argv.includes('--check')) {
  const current = existsSync(output) ? readFileSync(output, 'utf8') : ''
  if (current !== generated) {
    console.error('dist-phone/codex-data.js is stale — run: node scripts/build-phone-engine.js')
    process.exit(1)
  }
  console.log(`phone engine current · ${produced.length} exports · ${SOURCES.length} sources`)
  process.exit(0)
}

writeFileSync(output, generated)
const added = produced.filter(name => !REQUIRED_EXPORTS.includes(name))
console.log(`wrote ${output}`)
console.log(`  ${SOURCES.length} sources · ${produced.length} exports · ${(generated.length / 1024).toFixed(1)} KB`)
if (added.length) console.log(`  new since the shipped build: ${added.join(', ')}`)
